// Writes demo/CREDITS.md: who made each cover picture used in the online demos, and the licence it is under.
// Those pictures are NOT covered by the project's MIT licence; each keeps its own.
//
//   node scripts/write-demo-credits.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const credits = JSON.parse(fs.readFileSync(path.join(root, "demo", "credits.json"), "utf8"));
const rows = fs.readFileSync(path.join(root, "demo", "sampleData.js"), "utf8");
const rowPattern = /^\s*\["([a-z0-9-]+)", "((?:[^"\\]|\\.)+)", "([A-Za-z ]+)"/gm;
const titles = new Map([...rows.matchAll(rowPattern)].map((m) => [m[1], { title: m[2], type: m[3] }]));

const clean = (s) => String(s || "").replace(/(Unknown author)+/g, "Unknown author").replace(/\s+/g, " ").replace(/\|/g, "/").trim();
const lines = [
  "# Credits for the demo's pictures",
  "",
  "The online demos (`docs/demo/` and the phone demo built from `mobile/`) show real works with their real cover pictures, all taken from Wikimedia Commons and all public domain, Creative Commons or open-source.",
  "**These pictures are not covered by this project's MIT licence.** Each keeps the licence listed below, and the titles and artwork belong to their makers. If you reuse one, follow its licence (for Creative Commons \"BY\" and \"BY-SA\" pictures that means crediting the author, as below).",
  "",
  "Generated by `scripts/write-demo-credits.js` from `demo/credits.json`, which `scripts/fetch-demo-art.js` fills in from Commons (it refuses any picture whose licence is not on its allowed list).",
  "",
  "| Item | Type | Picture by | Licence | Source |",
  "|---|---|---|---|---|",
];
let missing = 0;
let count = 0;
for (const [slug, c] of Object.entries(credits)) {
  const t = titles.get(slug);
  if (!t) { missing++; continue; }
  count++;
  lines.push(`| ${clean(t.title)} | ${t.type} | ${clean(c.author).slice(0, 110)} | ${clean(c.licence)} | [Commons](${c.source}) |`);
}
fs.writeFileSync(path.join(root, "demo", "CREDITS.md"), lines.join("\n") + "\n");
console.log(`Wrote demo/CREDITS.md (${count} pictures${missing ? `, ${missing} in credits.json have no item in the demo` : ""}).`);
